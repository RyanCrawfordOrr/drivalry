import 'package:flutter/material.dart';
import 'package:flutter/services.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:qr_flutter/qr_flutter.dart';
import 'package:share_plus/share_plus.dart';

import '../../data/repos/circles_repo.dart';
import '../../data/repos/circles_sync.dart';

/// Invite code, QR and share button for a circle.
Future<void> showCircleInviteSheet(BuildContext context, Circle circle) {
  return showModalBottomSheet<void>(
    context: context,
    showDragHandle: true,
    isScrollControlled: true,
    builder: (ctx) => _InviteSheet(circle: circle),
  );
}

class _InviteSheet extends ConsumerWidget {
  const _InviteSheet({required this.circle});
  final Circle circle;

  @override
  Widget build(BuildContext context, WidgetRef ref) {
    final theme = Theme.of(context);
    // The code is generated by the server; a circle created seconds ago may
    // not have synced yet.
    final live = ref.watch(circleProvider(circle.id)) ?? circle;
    final code = live.inviteCode;
    if (code.isEmpty) {
      return SafeArea(
        child: Padding(
          padding: const EdgeInsets.all(24),
          child: Column(
            mainAxisSize: MainAxisSize.min,
            children: [
              Text('Invite to ${live.name}', style: theme.textTheme.titleLarge),
              const SizedBox(height: 16),
              const Text(
                'The invite code is still syncing. Check your connection and '
                'try again in a moment.',
                textAlign: TextAlign.center,
              ),
              const SizedBox(height: 16),
              FilledButton.tonal(
                onPressed: () => ref.read(myCirclesProvider.notifier).refresh(),
                child: const Text('Refresh'),
              ),
            ],
          ),
        ),
      );
    }
    final link = live.inviteLink;
    return SafeArea(
      child: Padding(
        padding: const EdgeInsets.fromLTRB(24, 0, 24, 24),
        child: Column(
          mainAxisSize: MainAxisSize.min,
          children: [
            Text('Invite to ${live.name}', style: theme.textTheme.titleLarge),
            const SizedBox(height: 8),
            Text(
              'Everyone in a circle sees everyone\'s live location, unless '
              'they hide.',
              style: theme.textTheme.bodySmall,
              textAlign: TextAlign.center,
            ),
            const SizedBox(height: 16),
            Container(
              padding: const EdgeInsets.all(12),
              decoration: BoxDecoration(
                color: Colors.white,
                borderRadius: BorderRadius.circular(12),
              ),
              child: QrImageView(data: link, size: 200),
            ),
            const SizedBox(height: 16),
            SelectableText(
              code.toUpperCase(),
              style: theme.textTheme.headlineSmall?.copyWith(
                letterSpacing: 4,
                fontFeatures: const [FontFeature.tabularFigures()],
              ),
            ),
            Text(
              'Friends enter this code under Circles, or open the link.',
              style: theme.textTheme.bodySmall,
              textAlign: TextAlign.center,
            ),
            const SizedBox(height: 16),
            Row(
              children: [
                Expanded(
                  child: OutlinedButton.icon(
                    onPressed: () async {
                      await Clipboard.setData(ClipboardData(text: link));
                      if (context.mounted) {
                        ScaffoldMessenger.of(context).showSnackBar(
                          const SnackBar(content: Text('Link copied')),
                        );
                      }
                    },
                    icon: const Icon(Icons.copy_outlined),
                    label: const Text('Copy link'),
                  ),
                ),
                const SizedBox(width: 12),
                Expanded(
                  child: FilledButton.icon(
                    onPressed: () => SharePlus.instance.share(
                      ShareParams(
                        text:
                            'Join my Drivalry circle "${live.name}": $link '
                            '(code ${code.toUpperCase()})',
                        subject: 'Drivalry circle invite',
                      ),
                    ),
                    icon: const Icon(Icons.share_outlined),
                    label: const Text('Share'),
                  ),
                ),
              ],
            ),
          ],
        ),
      ),
    );
  }
}
