/// Invite code, QR and share button for a circle.
Future<void> showCircleInviteSheet(BuildContext context, Circle circle) {
  return showDrivalrySheet<void>(
    context,
    title: 'Invite to ${circle.name}',
    builder: (ctx) => Padding(
      padding: sheetBottomInset(ctx),
      child: _InviteSheet(circle: circle),
    ),
  );
}

class _InviteSheet extends ConsumerWidget {
  const _InviteSheet({required this.circle});
  final Circle circle;

  @override
  Widget build(BuildContext context, WidgetRef ref) {
    // The code is generated by the server; a circle created seconds ago may
    // not have one yet.
    final live = ref.watch(circleProvider(circle.id)) ?? circle;
    final code = live.inviteCode;
    if (code.isEmpty) {
      return Column(
        mainAxisSize: MainAxisSize.min,
        crossAxisAlignment: CrossAxisAlignment.stretch,
        children: [
          Text(
            'The invite code is still on its way. Check your connection and '
            'try again in a moment.',
            style: context.bodyMuted,
          ),
          const SizedBox(height: Space.lg),
          SecondaryButton(
            label: 'Try again',
            onPressed: () => ref.read(myCirclesProvider.notifier).refresh(),
          ),
        ],
      );
    }
    final link = live.inviteLink;
    return Column(
      mainAxisSize: MainAxisSize.min,
      crossAxisAlignment: CrossAxisAlignment.stretch,
      children: [
        Text(
          'Everyone in a circle sees everyone\'s live location, unless they '
          'hide.',
          style: context.caption,
        ),
        const SizedBox(height: Space.lg),
        Center(
          child: Container(
            padding: const EdgeInsets.all(Space.md),
            decoration: BoxDecoration(
              // QR codes need a white quiet zone whatever the theme.
              color: Colors.white,
              borderRadius: Radii.tileRadius,
            ),
            child: QrImageView(data: link, size: 200),
          ),
        ),
        const SizedBox(height: Space.lg),
        SelectableText(
          code.toUpperCase(),
          textAlign: TextAlign.center,
          style: context.headline.copyWith(
            letterSpacing: 4,
            fontFeatures: const [FontFeature.tabularFigures()],
          ),
        ),
        const SizedBox(height: Space.xs),
        Text(
          'Friends type this code under Circles, or open the link.',
          style: context.caption,
          textAlign: TextAlign.center,
        ),
        const SizedBox(height: Space.lg),
        PrimaryButton(
          label: 'Share',
          icon: Icons.share_outlined,
          onPressed: () => SharePlus.instance.share(
            ShareParams(
              text:
                  'Join my Drivalry circle "${live.name}": $link '
                  '(code ${code.toUpperCase()})',
              subject: 'Drivalry circle invite',
            ),
          ),
        ),
        TextButton(
          onPressed: () async {
            await Clipboard.setData(ClipboardData(text: link));
            if (context.mounted) {
              ScaffoldMessenger.of(
                context,
              ).showSnackBar(const SnackBar(content: Text('Link copied')));
            }
          },
          child: const Text('Copy link'),
        ),
      ],
    );
  }
}
